private class SlotUi(slot: StudySlot) {
    var date by mutableStateOf(slot.date)
    var time by mutableIntStateOf(slot.time)
    var keep by mutableStateOf(true)
}

/** Plan de repaso de un examen: N sesiones de foco repartidas antes de la fecha. */
@Composable
fun StudyPlanScreen(data: AppData, examId: String, onClose: () -> Unit) {
    val ui = LocalUi.current
    val ctx = LocalContext.current
    val scope = rememberCoroutineScope()
    val exam = data.tasks.firstOrNull { it.id == examId }
    val examDate = parseDate(exam?.due)

    var sessions by remember { mutableIntStateOf(4) }
    var minutes by remember { mutableIntStateOf(60) }
    var loading by remember { mutableStateOf(false) }
    var note by remember { mutableStateOf<String?>(null) }
    val slots = remember { mutableStateListOf<SlotUi>() }
    var generated by remember { mutableStateOf(false) }

    Column(Modifier.fillMaxSize()) {
        ScreenHeader("Plan de repaso", onClose, close = true)
        if (exam == null || examDate == null) {
            Text(
                "Este examen no tiene fecha. Ponle una para poder repartir el repaso.",
                color = ui.muted, fontSize = 15.sp, fontWeight = FontWeight.SemiBold, modifier = Modifier.padding(16.dp)
            )
        } else PlanBody(data, exam, examDate, sessions, { sessions = it }, minutes, { minutes = it }, loading, { loading = it }, note, { note = it }, slots, generated, { generated = it }, onClose)
    }
}

@Composable
private fun ColumnScope.PlanBody(
    data: AppData, exam: TaskItem, examDate: LocalDate,
    sessions: Int, setSessions: (Int) -> Unit,
    minutes: Int, setMinutes: (Int) -> Unit,
    loading: Boolean, setLoading: (Boolean) -> Unit,
    note: String?, setNote: (String?) -> Unit,
    slots: MutableList<SlotUi>,
    generated: Boolean, setGenerated: (Boolean) -> Unit,
    onClose: () -> Unit
) {
    val ui = LocalUi.current
    val ctx = LocalContext.current
    val scope = rememberCoroutineScope()
    run {
        val today = LocalDate.now()
        val days = Gemini.studyDays(today, examDate)

        Column(Modifier.weight(1f).verticalScroll(rememberScrollState()).padding(horizontal = 16.dp)) {
            val subject = data.subject(exam.subjectId)?.name
            SerifText(subject ?: exam.title, fontSize = 26.sp, modifier = Modifier.padding(top = 6.dp))
            Text(
                "Examen ${dueLabel(examDate, today).lowercase()}" + (exam.time?.let { " a las " + minStr(it) } ?: "") +
                    " · ${days.size} " + if (days.size == 1) "día para repasar" else "días para repasar",
                color = ui.muted, fontSize = 14.sp, fontWeight = FontWeight.SemiBold, modifier = Modifier.padding(top = 4.dp)
            )

            if (days.isEmpty()) {
                Text("Ya no quedan días antes del examen.", color = ui.ink, fontSize = 15.sp, fontWeight = FontWeight.Bold, modifier = Modifier.padding(top = 16.dp))
            }

            if (days.isNotEmpty() && !generated && !loading) {
                Spacer(Modifier.height(18.dp))
                Stepper("Sesiones", "$sessions", { setSessions((sessions - 1).coerceAtLeast(1)) }, { setSessions((sessions + 1).coerceAtMost(minOf(10, days.size * 2))) })
                Text("Duración", color = ui.ink, fontWeight = FontWeight.ExtraBold, fontSize = 15.sp, modifier = Modifier.padding(top = 10.dp, bottom = 8.dp))
                Row(horizontalArrangement = Arrangement.spacedBy(8.dp)) {
                    listOf(30, 45, 60, 90).forEach { m ->
                        SelectChip("$m min", minutes == m, { setMinutes(m) }, Modifier.weight(1f), center = true)
                    }
                }
                Text(
                    "Cada sesión es un foco de $minutes min. Al terminarlo, la sesión queda hecha y te da el XP del foco.",
                    color = ui.muted, fontSize = 13.sp, fontWeight = FontWeight.SemiBold, modifier = Modifier.padding(top = 12.dp)
                )
            }

            if (loading) {
                Column(Modifier.fillMaxWidth().padding(top = 60.dp), horizontalAlignment = Alignment.CenterHorizontally) {
                    LoadingDots()
                    Text("Organizando…", color = ui.ink, fontWeight = FontWeight.Black, fontSize = 22.sp, modifier = Modifier.padding(top = 22.dp))
                }
            }

            if (generated) {
                note?.let { Text(it, color = ui.muted, fontSize = 13.sp, fontWeight = FontWeight.SemiBold, modifier = Modifier.padding(top = 12.dp)) }
                Spacer(Modifier.height(12.dp))
                slots.forEach { s ->
                    ChunkyCard(Modifier.fillMaxWidth().padding(bottom = 10.dp), padding = 0.dp, radius = 16.dp) {
                        Row(Modifier.padding(horizontal = 14.dp, vertical = 12.dp), verticalAlignment = Alignment.CenterVertically) {
                            CheckCircle(s.keep, { s.keep = !s.keep })
                            Column(Modifier.weight(1f).padding(start = 12.dp)) {
                                Text(
                                    "${dayName(s.date).replaceFirstChar { it.uppercase() }} ${s.date.dayOfMonth} · ${minStr(s.time)}",
                                    color = if (s.keep) ui.ink else ui.muted, fontWeight = FontWeight.Black, fontSize = 16.sp
                                )
                                Text("$minutes min de foco", color = ui.muted, fontWeight = FontWeight.SemiBold, fontSize = 13.sp)
                            }
                            MiniTap(Ic.chevronLeft) {
                                val n = s.date.minusDays(1)
                                if (n in days) s.date = n
                            }
                            MiniTap(Ic.chevronRight) {
                                val n = s.date.plusDays(1)
                                if (n in days) s.date = n
                            }
                            MiniTap(Ic.minus) { s.time = (s.time - 15).coerceAtLeast(7 * 60) }
                            MiniTap(Ic.plus) { s.time = (s.time + 15).coerceAtMost(22 * 60) }
                        }
                    }
                }
                TextAction("Cambiar sesiones o duración", { setGenerated(false); slots.clear() }, Modifier.fillMaxWidth())
            }
            Spacer(Modifier.height(16.dp))
        }

        Column(Modifier.padding(horizontal = 16.dp).padding(bottom = 16.dp)) {
            if (days.isNotEmpty() && !generated && !loading) {
                ChunkyButton("Organizar", {
                    setLoading(true)
                    setNote(null)
                    scope.launch {
                        val result: List<StudySlot>? = if (SecretStore.hasGeminiKey()) {
                            try {
                                Gemini.studyPlan(Repo.data, exam, sessions, minutes).takeIf { it.isNotEmpty() }
                            } catch (e: AiError) {
                                setNote("${e.message} Lo he repartido yo.")
                                null
                            } catch (e: kotlinx.coroutines.CancellationException) {
                                throw e
                            } catch (e: Exception) {
                                setNote("La IA ha fallado. Lo he repartido yo.")
                                null
                            }
                        } else {
                            setNote("Sin clave de IA: lo he repartido yo, después de clase.")
                            null
                        }
                        val plan = result ?: localPlan(Repo.data, days, sessions, minutes)
                        slots.clear()
                        plan.forEach { slots += SlotUi(it) }
                        setLoading(false)
                        setGenerated(true)
                    }
                }, Modifier.fillMaxWidth())
            } else if (generated) {
                val n = slots.count { it.keep }
                ChunkyButton("Añadir plan · $n " + if (n == 1) "sesión" else "sesiones", {
                    val title = "Repasar " + (data.subject(exam.subjectId)?.name ?: exam.title)
                    val tasks = slots.filter { it.keep }.sortedWith(compareBy({ it.date }, { it.time })).map { s ->
                        TaskItem(
                            id = Repo.newId(),
                            title = title,
                            kind = Kind.REPASO,
                            areaId = exam.areaId,
                            subjectId = exam.subjectId,
                            due = s.date.key(),
                            time = s.time,
                            createdAt = System.currentTimeMillis(),
                            examId = exam.id,
                            minutes = minutes
                        )
                    }
                    Repo.addTasks(tasks)
                    Toast.makeText(ctx, "Plan añadido. Pulsa ▶ en cada sesión para empezar el foco.", Toast.LENGTH_LONG).show()
                    onClose()
                }, Modifier.fillMaxWidth(), enabled = n > 0)
            }
        }
    }
}

@Composable
private fun MiniTap(icon: Int, onClick: () -> Unit) {
    val ui = LocalUi.current
    Box(Modifier.size(32.dp).clip(CircleShape).clickable(onClick = onClick), contentAlignment = Alignment.Center) {
        UIcon(icon, ui.muted, size = 18.dp)
    }
}

/** Reparto sin IA: días espaciados hasta el examen, después de clase o por la mañana el fin de semana. */
internal fun localPlan(d: AppData, days: List<LocalDate>, sessions: Int, minutes: Int): List<StudySlot> {
    if (days.isEmpty()) return emptyList()
    val today = LocalDate.now()
    val out = mutableListOf<StudySlot>()
    // Más sesiones cerca del examen: se recorren los días desde el final.
    val order = days.reversed()
    var round = 0
    while (out.size < sessions && round < 2) {
        val step = if (round == 0) maxOf(1, order.size / sessions.coerceAtLeast(1)) else 1
        var i = 0
        while (i < order.size && out.size < sessions) {
            val day = order[i]
            val taken = out.filter { it.date == day }
            if (taken.size <= round) {
                val start = baseTime(d, day) + taken.size * (minutes + 30)
                val time = freeFrom(d, day, start, minutes)
                val okToday = day != today || time >= nowMin() + 30
                if (time + minutes <= 22 * 60 && okToday) out += StudySlot(day, time)
            }
            i += step
        }
        round++
    }
    return out.sortedWith(compareBy({ it.date }, { it.time }))
}

private fun baseTime(d: AppData, day: LocalDate): Int {
    val weekend = day.dayOfWeek == DayOfWeek.SATURDAY || day.dayOfWeek == DayOfWeek.SUNDAY
    if (weekend) return 10 * 60 + 30
    val b = d.block
    if (b.enabled && b.scheduleEnabled && day.dayOfWeek.value in b.days) return b.from
    val classEnd = classesOn(d, day).lastOrNull()?.period?.end ?: (14 * 60)
    return maxOf(17 * 60, classEnd + 120)
}

/** Empuja la hora hasta que no choque con eventos ni tareas con hora. */
private fun freeFrom(d: AppData, day: LocalDate, start: Int, minutes: Int): Int {
    val busy = eventsOn(d, day).map { it.start to it.end } +
        d.tasks.filter { !it.done && it.due == day.key() }.mapNotNull { t -> t.time?.let { tm -> tm to tm + (t.minutes ?: 30) } }
    var t = start
    repeat(12) {
        val clash = busy.firstOrNull { (s, e) -> t < e && t + minutes > s } ?: return t
        t = clash.second + 15
    }
    return t
}
